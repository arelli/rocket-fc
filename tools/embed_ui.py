# PlatformIO pre-build script (ground station): embeds tools/ground_station.html,
# gzip-compressed, as a byte array so the ground station can serve the UI over
# WiFi. The generated header is not committed (.gitignore); it is rebuilt from
# the HTML on every build, so the served UI always matches the file.
Import("env")  # noqa: F821  (provided by PlatformIO)

import gzip
import os

proj = env["PROJECT_DIR"]  # noqa: F821
src = os.path.join(proj, "tools", "ground_station.html")
dst = os.path.join(proj, "src", "ground", "ui_html_gz.h")

with open(src, "rb") as f:
    html = f.read()
gz = gzip.compress(html, compresslevel=9, mtime=0)  # mtime=0: same input, same bytes

lines = ["// GENERATED by tools/embed_ui.py from tools/ground_station.html. Do not edit.",
         "#pragma once", "#include <stddef.h>", "#include <stdint.h>",
         "static const size_t kUiHtmlGzLen = %d;" % len(gz),
         "static const uint8_t kUiHtmlGz[] = {"]
for i in range(0, len(gz), 20):
    lines.append("  " + ",".join(str(b) for b in gz[i:i + 20]) + ",")
lines.append("};")
text = "\n".join(lines) + "\n"
old = open(dst).read() if os.path.exists(dst) else ""
if old != text:  # rewrite only on change (keeps incremental builds incremental)
    with open(dst, "w") as f:
        f.write(text)
print("rocket-fc build: UI embedded (%d bytes, %d gzipped)" % (len(html), len(gz)))
